export type PhoneResult = { ok: true; number: string } | { ok: false; error: string }

export function validatePhone(input: string): PhoneResult {
  if (!input) return { ok: false, error: 'Please enter your number.' }
  if (/\s/.test(input)) return { ok: false, error: 'Remove spaces. Enter like +919876543210 (+, country code, number).' }
  if (!/^\+\d+$/.test(input)) return { ok: false, error: "Number must start with a single '+' followed by digits only (e.g., +919876543210)." }
  const digits = input.slice(1)
  if (digits[0] === '0') return { ok: false, error: 'Country code cannot start with 0. Enter +, country code, then number.' }
  if (digits.length < 8 || digits.length > 15) return { ok: false, error: 'Number length is invalid. Include the country code (e.g., +919876543210).' }

  let code: string | null = null
  for (let len = 1; len <= 3; len++) {
    if (COUNTRY_RULES[digits.slice(0, len)]) {
      code = digits.slice(0, len)
      break
    }
  }
  if (!code) return { ok: false, error: 'Country code not recognised. Enter + then country code, then your number.' }

  const national = digits.slice(code.length)
  const [min, max] = COUNTRY_RULES[code]
  if (national.length < min || national.length > max) {
    return {
      ok: false,
      error: `+${code} numbers need ${min === max ? min : `${min}-${max}`} digits after the country code. You may have missed the country code.`,
    }
  }
  if (code === '91' && !/^[6-9]/.test(national)) {
    return { ok: false, error: 'Indian numbers must start with 6, 7, 8 or 9 after +91.' }
  }
  return { ok: true, number: input }
}
